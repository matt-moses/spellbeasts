// Writes the build stamp: version.json (fetched fresh by the page) and js/logic/build.js (what the page is running).
// Also writes sw-assets.js (the offline file list). Runs automatically in .githooks/pre-commit; you can also run `npm run stamp`.
import { writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { execSync } from 'node:child_process';
const d = new Date();
const p = (n) => String(n).padStart(2, '0');
let sha = 'dev';
try { sha = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { /* no git */ }
const version = `${d.getUTCFullYear()}.${p(d.getUTCMonth() + 1)}${p(d.getUTCDate())}.${p(d.getUTCHours())}${p(d.getUTCMinutes())}`;
const root = new URL('../', import.meta.url);
writeFileSync(new URL('version.json', root), JSON.stringify({ version }) + '\n');
writeFileSync(new URL('js/logic/build.js', root), `// Generated by tools/stamp-version.mjs. Do not edit.\nexport const BUILD_VERSION = '${version}';\n`);
// Everything the app needs offline. The service worker precaches exactly this list, under a cache named by the version.
const rootPath = new URL('../', import.meta.url).pathname;
const walk = (dir) => readdirSync(join(rootPath, dir)).flatMap((f) => { const rel = `${dir}/${f}`; return statSync(join(rootPath, rel)).isDirectory() ? walk(rel) : [rel]; });
const assets = ['./', 'index.html', 'manifest.webmanifest', ...walk('css'), ...walk('js'), ...walk('data'), ...walk('icons')].sort();
writeFileSync(new URL('sw-assets.js', root), `// Generated by tools/stamp-version.mjs. Do not edit.\nself.SW_VERSION = '${version}';\nself.SW_ASSETS = ${JSON.stringify(assets, null, 2)};\n`);
console.log(`stamped ${version} (after ${sha})`);
